def command_help(in_guild, category='overview'):
    category = category if category in HELP_CATEGORIES else 'overview'
    embed = discord.Embed(title='ジョージのコマンド案内｜' + HELP_CATEGORIES[category], color=0xE2AD48)
    if category == 'overview':
        embed.description = 'やりたいことから選んでくれ！ `/ヘルプ` の「分類」を選ぶと詳しい使い方が見られるぜ。'
        embed.add_field(name='まず使ってみるなら', inline=False, value=(
            '話す → サーバーで `@ジョージ`、DMならそのまま\n'
            '遊ぶ → `/おみくじ`・`/ガチャ`\n'
            'カードを見る → `/所持カード`\n'
            '時間になったら呼んでほしい → `/タイマー`・`/予定`（予定はサーバー専用）'))
        for key, label in HELP_CATEGORIES.items():
            if key != 'overview':
                embed.add_field(name=label, value=f'`/ヘルプ 分類:{label}`', inline=False)
    else:
        for name, value in SECTIONS[category]:
            embed.add_field(name=name, value=value, inline=False)
    if not in_guild:
        embed.add_field(name='今はDMだぜ！', value='予定・共有記憶・季節通知・行事のコマンドはサーバー専用。サーバーのチャンネルで使ってくれ。', inline=False)
    embed.set_footer(text='一覧に戻るなら /ヘルプ。コマンドの項目はDiscordの候補から選んでくれ！')
    return embed
