def command_help(in_guild, category='overview'):
    category = category if category in HELP_CATEGORIES else 'overview'
    embed = discord.Embed(title='ジョージのコマンド案内｜' + HELP_CATEGORIES[category], color=0xE2AD48)
    if category == 'overview':
        embed.description = '俺にできることはこれだぜ！ 詳しくは `/ヘルプ` の「分類」から選んでくれ。'
        summaries = {
            'chat': '話しかける・画像を見せる・プログレスを調べる。',
            'gacha': 'ガチャ・おみくじで遊ぶ。カードを集めてお気に入りを選ぶ。',
            'seasonal': '祝日や季節の行事に挨拶。サーバーの記念日も登録できる。',
            'system': 'ジョージの動作状況や、保存・利用条件を確認。',
        }
        for key, label in HELP_CATEGORIES.items():
            if key != 'overview':
                embed.add_field(name=label, value=f'{summaries[key]}\n詳しく：`/ヘルプ 分類:{label}`', inline=False)
    else:
        for name, value in SECTIONS[category]:
            embed.add_field(name=name, value=value, inline=False)
    if not in_guild:
        embed.add_field(name='今はDMだぜ！', value='季節通知のコマンドはサーバー専用。サーバーのチャンネルで使ってくれ。', inline=False)
    embed.set_footer(text='一覧に戻るなら /ヘルプ。コマンドの項目はDiscordの候補から選んでくれ！')
    return embed
